# common 公共包初始化文件：仅用于标识该目录为 Python 包，具体能力由各子模块提供。
# 这里刻意不导入子模块，避免 common 被加载时连带触发 Django/数据库依赖，造成循环导入。
# 模块用途：承载跨 app 复用的基础设施（统一响应、权限、分页、雪花 ID、通用 CRUD 视图等）。
# 被谁调用：各 apps 通过 from common.response / common.views 等具体子模块导入，不依赖本文件导出。
# 关键约定：保持空导入是刻意设计；若在此处 import 子模块，会让 common 包在 Django 配置完成前被加载。
# 因此新增公共能力时请直接添加子模块文件，不要在本文件里 re-export，以免引入循环依赖。
